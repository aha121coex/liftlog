const base = new URL(self.registration.scope);
const digest = async bytes => Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes)),x=>x.toString(16).padStart(2,'0')).join('');
self.addEventListener('install',event=>{
  event.waitUntil((async()=>{
    const cache=await caches.open(CACHE);
    try {
      for(const [path,expected] of Object.entries(ASSET_HASHES)){
        const url=new URL(path,base).href;
        const response=await fetch(url,{cache:'no-store'});
        if(!response.ok||await digest(await response.clone().arrayBuffer())!==expected)throw Error('Incomplete LiftLog release: '+path);
        await cache.put(url,response);
      }
    }catch(error){await caches.delete(CACHE);throw error;}
  })());
});
self.addEventListener('activate',event=>{
  event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>(key.startsWith('liftlog-shell-')||key.startsWith('liftlog-app-shell-'))&&key!==CACHE).map(key=>caches.delete(key)))));
});
self.addEventListener('fetch',event=>{
  if(event.request.method!=='GET')return;
  const url=new URL(event.request.url);
  if(url.origin!==base.origin||!url.pathname.startsWith(base.pathname))return;
  const path='./'+url.pathname.slice(base.pathname.length);
  if(!Object.hasOwn(ASSET_HASHES,path)&&event.request.mode!=='navigate')return;
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    const target=event.request.mode==='navigate'?'./index.html':path;
    return await cache.match(new URL(target,base).href)||Response.error();
  })());
});
