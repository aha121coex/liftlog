"""Generate verified shell hashes. Run after editing any shipped asset."""
import hashlib
import json
from pathlib import Path
import re
import sys
root = Path(__file__).resolve().parents[1]
paths = ['index.html','styles.css','cardio.js','program.js','app.js','manifest.webmanifest','icon-192.png','icon-512.png','apple-touch-icon.png']
hashes = {'./'+p:hashlib.sha256((root/p).read_bytes()).hexdigest() for p in paths}
hashes['./'] = hashes['./index.html']
serialized = json.dumps(hashes,sort_keys=True,separators=(',',':'))
version = hashlib.sha256(serialized.encode()).hexdigest()[:20]
p = root/'sw.js'
source = p.read_text()
updated = re.sub(r"const CACHE = '[^']+';", "const CACHE = 'liftlog-shell-"+version+"';",source)
updated = re.sub(r'const ASSET_HASHES = .*?; // generated by scripts/prepare-shell.py', 'const ASSET_HASHES = '+serialized+'; // generated by scripts/prepare-shell.py',updated)
if '--check' in sys.argv:
    if source != updated:
        raise SystemExit('Shell hashes are stale. Run python3 scripts/prepare-shell.py')
else:
    p.write_text(updated)
